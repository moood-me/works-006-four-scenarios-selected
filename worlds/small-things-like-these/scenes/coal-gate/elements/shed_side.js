// The coal shed's right side (on `shed`, its x running back from the front's corner, 0…2.6): the same grey-white
// rubble, its top falling from 2.5 m at the front to 2.15 m at the back under the slates.
g.save();
g.beginPath();
g.moveTo(0, 0.05);
g.lineTo(0, -2.5);
g.lineTo(2.6, -2.15);
g.lineTo(2.6, 0.05);
g.closePath();
