grime.addColorStop(0, "rgba(58, 56, 54, 0.5)");
grime.addColorStop(1, "rgba(58, 56, 54, 0)");
g.fillStyle = grime;
g.fillRect(0, -2.5, 2.6, 2.55);
g.restore();
g.fillStyle = "#4a4d52";
g.beginPath();
g.moveTo(-0.08, -2.48);
